#include <gtest/gtest.h>
#include <algorithm>
#include <arm_cell_interfaces/msg/motion_task_result_code.hpp>
#include <fstream>
#include <iostream>
#include <sstream>
#include <nlohmann/json.hpp>
#include <rclcpp/rclcpp.hpp>
#include <moveit/robot_model_loader/robot_model_loader.h>
#include <moveit/robot_trajectory/robot_trajectory.h>
#include <moveit/planning_scene/planning_scene.h>
#include <geometric_shapes/shapes.h>
#include "arm_cell_motion/taught_motion.hpp"
#include "arm_cell_motion/taught_motion_trajectory.hpp"
#include "arm_cell_motion/trajectory_generation.hpp"


TEST(TeachingModel, GeneratesCompleteConfiguredTapeMotionsWithoutSceneOrPlanner)
{
  using namespace arm_cell_motion;
  using Code = arm_cell_interfaces::msg::MotionTaskResultCode;
  const auto * input = std::getenv("ARM_CELL_MODEL_TEST_INPUT");
  ASSERT_NE(input, nullptr);
  nlohmann::json data;
  std::ifstream(input) >> data;
  const auto & config = data.at("configuration");
  const auto & model_config = config.at("model_configuration");
  const auto group_name = model_config.at("planning_group").get<std::string>();
  std::ifstream semantic_file(model_config.at("semantic").get<std::string>());
  std::stringstream semantic; semantic << semantic_file.rdbuf();
  rclcpp::init(0, nullptr);
  std::vector<rclcpp::Parameter> parameters{
    {"robot_description", data.at("urdf").get<std::string>()},
    {"robot_description_semantic", semantic.str()}};
  for (const auto & item : data.at("kinematics").at(group_name).items()) {
    const auto key = "robot_description_kinematics." + group_name + "." + item.key();
    if (item.value().is_string()) {parameters.emplace_back(key, item.value().get<std::string>());}
    else {parameters.emplace_back(key, item.value().get<double>());}
  }
  const auto & motion = config.at("motion");
  for (auto & parameter : parameters) {
    if (parameter.get_name() == "robot_description_kinematics." + group_name + ".kinematics_solver") {
      parameter = rclcpp::Parameter(parameter.get_name(), motion.at("pick_ik_solver").get<std::string>());
    }
  }
  parameters.emplace_back("robot_description_kinematics." + group_name + ".solve_type",
    motion.at("pick_ik_solve_type").get<std::string>());
  auto node = std::make_shared<rclcpp::Node>("teaching_model_test",
    rclcpp::NodeOptions().automatically_declare_parameters_from_overrides(true)
    .parameter_overrides(parameters));
  robot_model_loader::RobotModelLoader loader(node);
  auto model = loader.getModel();
  ASSERT_NE(model, nullptr);
  const auto * group = model->getJointModelGroup(group_name);
  ASSERT_NE(group, nullptr);
  ASSERT_NE(group->getSolverInstance(), nullptr);
  auto source_solver = std::const_pointer_cast<kinematics::KinematicsBase>(group->getSolverInstance());
  const auto timeout = source_solver->getDefaultTimeout();
  source_solver->setDefaultTimeout(.37);
  model = make_kinematic_model(model, group_name, source_solver);
  ASSERT_DOUBLE_EQ(source_solver->getDefaultTimeout(), .37)
    << "Teaching model must not change another consumer's solver timeout";
  source_solver->setDefaultTimeout(timeout);
  group = model->getJointModelGroup(group_name);
  const auto names = motion.at("arm_joint_names").get<std::vector<std::string>>();
  const auto limits = joint_motion_limits_from_urdf(data.at("urdf").get<std::string>(), names,
    motion.at("planning_max_acceleration_rad_s2").get<double>());
  const auto registry = parse_taught_motions(motion.at("taught_motions_json").get<std::string>(),
    config.at("home_joint_positions").get<std::vector<double>>(),
    config.at("home_joint_positions").get<std::vector<double>>(), names.size());
  if (data.contains("linear_replay")) {
    // Replay only the failed place descent, with the measured start from the
    // 2026-11-20 Tape C10 Long run. No Scene or simulator is involved.
    const auto & replay = data.at("linear_replay");
    const auto positions = replay.at("start_joint_positions").get<std::vector<double>>();
    const auto recorded_pose = replay.at("target_tcp_pose").get<std::vector<double>>();
    const auto & descent = registry.at("tape_transfer").cartesian_waypoints.at(5);
    ASSERT_EQ(descent.motion, "MoveL");
    ASSERT_EQ(recorded_pose.size(), descent.pose.size());
    // Keep the exact failure regression and validate this same movement as
    // generated by the current local teaching settings.
    const std::vector<std::vector<double>> targets{recorded_pose,
      std::vector<double>(descent.pose.begin(), descent.pose.end())};
    for (const auto & pose : targets) {
      Eigen::Isometry3d target = Eigen::Isometry3d::Identity();
      target.translation() = Eigen::Vector3d(pose[0], pose[1], pose[2]);
      target.linear() = Eigen::Quaterniond(pose[6], pose[3], pose[4], pose[5]).toRotationMatrix();
      std::vector<std::vector<double>> previous_path;
      for (int repeat = 0; repeat < 3; ++repeat) {
        moveit::core::RobotState start(model); start.setToDefaultValues();
        start.setJointGroupPositions(group, positions); start.update();
        moveit_msgs::msg::RobotTrajectory generated;
        LinearJointChangeDiagnostics diagnostics;
        ASSERT_EQ(generate_linear_joint_trajectory(start, group_name, "sf_grasp_tcp", target,
          generated, {}, &diagnostics), Code::TASK_RESULT_SUCCESS);
        EXPECT_TRUE(diagnostics.available);
        EXPECT_GT(diagnostics.exceeding_step_count, 0U)
          << "The recorded descent must exercise the former rejection criterion";
        EXPECT_EQ(diagnostics.joint_names, names);
        EXPECT_EQ(diagnostics.maximum_step_joint_deltas.size(), names.size());
        ASSERT_GE(generated.joint_trajectory.points.size(), 2U);
        const Eigen::Vector3d origin = start.getGlobalLinkTransform("sf_grasp_tcp").translation();
        const Eigen::Vector3d direction = target.translation() - origin;
        const Eigen::Quaterniond initial_orientation(start.getGlobalLinkTransform("sf_grasp_tcp").linear());
        const Eigen::Quaterniond final_orientation(target.linear());
        moveit::core::RobotState sample(start);
        for (const auto & point : generated.joint_trajectory.points) {
          sample.setJointGroupPositions(group, point.positions); sample.update();
          EXPECT_TRUE(sample.satisfiesBounds(group));
          const auto actual = sample.getGlobalLinkTransform("sf_grasp_tcp");
          const double fraction = (actual.translation() - origin).dot(direction) / direction.squaredNorm();
          EXPECT_GE(fraction, -1e-3); EXPECT_LE(fraction, 1.001);
          EXPECT_LT((actual.translation() - origin - fraction * direction).norm(), 1e-4);
          const auto expected_orientation = initial_orientation.slerp(
            std::clamp(fraction, 0.0, 1.0), final_orientation).toRotationMatrix();
          EXPECT_LT(Eigen::AngleAxisd(actual.linear().transpose() * expected_orientation).angle(), 1e-3);
        }
        const auto actual = sample.getGlobalLinkTransform("sf_grasp_tcp");
        EXPECT_LT((actual.translation() - target.translation()).norm(), 1e-4);
        EXPECT_LT(Eigen::AngleAxisd(actual.linear().transpose() * target.linear()).angle(), 1e-3);
        if (!previous_path.empty()) {
          ASSERT_EQ(previous_path.size(), generated.joint_trajectory.points.size());
          for (std::size_t i = 0; i < previous_path.size(); ++i) {
            for (std::size_t j = 0; j < names.size(); ++j) {
              EXPECT_NEAR(generated.joint_trajectory.points[i].positions[j], previous_path[i][j], 1e-3);
            }
          }
        }
        previous_path.clear();
        for (const auto & point : generated.joint_trajectory.points) {
          previous_path.push_back(point.positions);
        }
        std::cout << "place descent repeat=" << repeat
                  << " target_z=" << pose[2]
                  << " points=" << generated.joint_trajectory.points.size()
                  << " diagnostic_exceeding_steps=" << diagnostics.exceeding_step_count
                  << " average_distance=" << diagnostics.average_step_distance
                  << " maximum_distance=" << diagnostics.maximum_step_distance << '\n';
        ASSERT_TRUE(retime_joint_trajectory(model, group_name, start, generated, .1, .1, &limits));
        for (const auto & point : generated.joint_trajectory.points) {
          for (std::size_t j = 0; j < limits.size(); ++j) {
            EXPECT_LE(std::abs(point.velocities[j]), limits[j].max_velocity * .1 + 1e-6);
            EXPECT_LE(std::abs(point.accelerations[j]), limits[j].max_acceleration * .1 + 1e-6);
          }
        }
      }
    }
    rclcpp::shutdown();
    return;
  }
  moveit::core::RobotState state(model); state.setToDefaultValues();
  state.setJointGroupPositions(group, config.at("home_joint_positions").get<std::vector<double>>());
  state.update();
  planning_scene::PlanningScene static_scene(model);
  for (const auto & box : config.at("cell").at("tape_roll").at("static_boxes")) {
    const auto size = box.at("geometry").at("dimensions_m").get<std::array<double, 3>>();
    const auto position = box.at("pose").at("position_m").get<std::array<double, 3>>();
    const auto rotation = box.at("pose").at("quaternion_xyzw").get<std::array<double, 4>>();
    const auto id = box.at("id").get<std::string>();
    Eigen::Isometry3d pose = Eigen::Isometry3d::Identity();
    pose.translation() = Eigen::Vector3d(position.data());
    pose.linear() = Eigen::Quaterniond(rotation[3], rotation[0], rotation[1], rotation[2])
      .toRotationMatrix();
    static_scene.getWorldNonConst()->addToObject(
      id, std::make_shared<shapes::Box>(size[0], size[1], size[2]), pose);
    if (id == "/World/TapeRollCell/RobotPedestal") {
      static_scene.getAllowedCollisionMatrixNonConst().setEntry("base_link", id, true);
    }
  }
  std::size_t blended_groups = 0;
  for (const auto * sequence : {"tape_approach", "tape_insert", "tape_transfer", "tape_retreat"}) {
    const auto & taught = registry.at(sequence);
    std::vector<trajectory_msgs::msg::JointTrajectory> blend_segments;
    moveit::core::RobotState blend_start(state);
    for (const auto & point : taught.cartesian_waypoints) {
      const bool blended = point.blend || !blend_segments.empty();
      if (blended && blend_segments.empty()) {blend_start = state;}
      SCOPED_TRACE(std::string(sequence) + ":" + point.motion);
      Eigen::Isometry3d target = Eigen::Isometry3d::Identity();
      target.linear() = Eigen::Quaterniond(point.pose[6], point.pose[3], point.pose[4], point.pose[5]).toRotationMatrix();
      target.translation() = Eigen::Vector3d(point.pose[0], point.pose[1], point.pose[2]);
      target = state.getGlobalLinkTransform("base_link") * target;
      trajectory_msgs::msg::JointTrajectory trajectory;
      if (point.motion == "MoveJ") {
        ASSERT_EQ(point.joint_positions.size(), names.size())
          << "Default Tape Cell MoveJ points must select a taught joint target";
        std::vector<double> start;
        state.copyJointGroupPositions(group, start);
        const auto generated = make_taught_joint_trajectory(names, start, point.joint_positions, limits,
          taught.velocity_scale, taught.acceleration_scale);
        ASSERT_TRUE(generated.valid) << generated.reason;
        trajectory = generated.trajectory;
      } else {
        ASSERT_EQ(point.motion, "MoveL");
        moveit_msgs::msg::RobotTrajectory generated;
        ASSERT_EQ(generate_linear_joint_trajectory(state, group_name, "sf_grasp_tcp", target, generated), Code::TASK_RESULT_SUCCESS);
        if (!blended) {
          ASSERT_TRUE(retime_joint_trajectory(model, group_name, state, generated,
            taught.velocity_scale, taught.acceleration_scale, &limits));
        }
        trajectory = generated.joint_trajectory;
      }
      ASSERT_GE(trajectory.points.size(), 2U);
      if (blended) {
        blend_segments.push_back(trajectory);
        if (point.blend) {
          state.setJointGroupPositions(group, trajectory.points.back().positions);
          state.update();
          continue;
        }
        moveit_msgs::msg::RobotTrajectory combined;
        ASSERT_TRUE(blend_taught_joint_paths(blend_segments, combined));
        EXPECT_EQ(combined.joint_trajectory.points.back().positions, trajectory.points.back().positions);
        ASSERT_TRUE(retime_joint_trajectory(model, group_name, blend_start, combined,
          taught.velocity_scale, taught.acceleration_scale, &limits));

        for (std::size_t i = 0; i + 1 < blend_segments.size(); ++i) {
          SCOPED_TRACE(i);
          const auto & junction = blend_segments[i].points.back().positions;
          const auto closest = std::min_element(
            combined.joint_trajectory.points.begin(), combined.joint_trajectory.points.end(),
            [&](const auto & first, const auto & second) {
              const Eigen::Map<const Eigen::VectorXd> q(junction.data(), junction.size());
              return (Eigen::Map<const Eigen::VectorXd>(first.positions.data(), q.size()) - q)
                     .squaredNorm() <
                     (Eigen::Map<const Eigen::VectorXd>(second.positions.data(), q.size()) - q)
                     .squaredNorm();
            });
          ASSERT_NE(closest, combined.joint_trajectory.points.end());
          const Eigen::Map<const Eigen::VectorXd> velocity(closest->velocities.data(), names.size());
          EXPECT_GT(velocity.norm(), 1e-3) << "The generated path stops at the blend junction";
        }
        moveit::core::RobotState collision_state(blend_start);
        for (const auto & sample : combined.joint_trajectory.points) {
          collision_state.setJointGroupPositions(group, sample.positions);
          collision_state.update();
          collision_detection::CollisionRequest request;
          request.contacts = true;
          collision_detection::CollisionResult collision;
          static_scene.checkCollision(request, collision, collision_state);
          if (collision.collision) {
            ASSERT_FALSE(collision.contacts.empty());
            FAIL() << collision.contacts.begin()->first.first << " contacts "
                   << collision.contacts.begin()->first.second;
          }
        }
        trajectory = std::move(combined.joint_trajectory);
        blend_segments.clear();
        ++blended_groups;
      }
      std::cout << sequence << " " << point.motion << " target_joints="
                << nlohmann::json(trajectory.points.back().positions).dump() << '\n';
      state.setJointGroupPositions(group, trajectory.points.back().positions); state.update();
      EXPECT_TRUE(state.satisfiesBounds(group));
      const auto actual = state.getGlobalLinkTransform("sf_grasp_tcp");
      EXPECT_LT((actual.translation() - target.translation()).norm(), 1e-4);
      EXPECT_LT(Eigen::AngleAxisd(actual.linear().transpose() * target.linear()).angle(), 1e-3);
      for (const auto & sample : trajectory.points) {
        for (std::size_t j = 0; j < limits.size(); ++j) {
          EXPECT_LE(std::abs(sample.velocities[j]), limits[j].max_velocity * taught.velocity_scale + 1e-6);
          EXPECT_LE(std::abs(sample.accelerations[j]), limits[j].max_acceleration * taught.acceleration_scale + 1e-6);
        }
      }
    }
  }
  EXPECT_EQ(blended_groups, 1U);
  // The next cycle starts from the retreat posture.
  const auto & approach = registry.at("tape_approach");
  std::vector<double> retreat;
  state.copyJointGroupPositions(group, retreat);
  const auto & joints = approach.cartesian_waypoints.front().joint_positions;
  const auto repeat = make_taught_joint_trajectory(
    names, retreat, joints, limits, approach.velocity_scale, approach.acceleration_scale);
  ASSERT_TRUE(repeat.valid) << repeat.reason;
  EXPECT_EQ(repeat.trajectory.points.front().positions, retreat);
  EXPECT_EQ(repeat.trajectory.points.back().positions, joints);
  rclcpp::shutdown();
}
